const COMMIT_KEY = "__adminSectionsCommit";
function currentSettings(config: AdminConfig): AdminConfig {
  return Object.fromEntries(Object.entries(config).filter(([key]) => !(key in ADMIN_SECTIONS) && key !== COMMIT_KEY)) as unknown as AdminConfig;
}
const copy = <T>(value: T): T => JSON.parse(JSON.stringify(value)) as T;
const entries = (config: AdminConfig | null, key: AdminSection): readonly Record<string, unknown>[] =>
  (config?.[key] ?? []) as unknown as readonly Record<string, unknown>[];
const itemId = (section: AdminSection, item: Record<string, unknown>): string => {
  const id = item[section === "methodStandings" ? "methodId" : section === "placeTargets" ? "key" : "id"];
  if (typeof id !== "string" || !id) throw new Error(`Invalid ${section} row identity`);
  return id;
};
function changes(held: AdminConfig | null, next: AdminConfig) {
  return (Object.keys(ADMIN_SECTIONS) as AdminSection[]).flatMap(section => {
    if (!(section in next)) return [];
    const before = new Map(entries(held, section).map(item => [itemId(section, item), item]));
    const after = new Map(entries(next, section).map(item => [itemId(section, item), item]));
    const put = [...after].filter(([id, item]) => canonicalJson(before.get(id)) !== canonicalJson(item)).map(([id, value]) => ({ id, value }));
    const remove = section === "placeTargets" || section === "billingFacts" ? [...before.keys()].filter(id => !after.has(id)) : [];
    return put.length || remove.length ? [{ section, put, remove }] : [];
  });
}
const scopeOf = (config: AdminConfig): AdminSectionsQuery => Object.fromEntries(
  (Object.keys(ADMIN_SECTIONS) as AdminSection[]).filter(key => key in config).map(key => [key, true]));

type Query = (text: string, params?: readonly unknown[]) => Promise<readonly Record<string, unknown>[]>;
const timestamp = (value: unknown): string => new Date(value as string).toISOString();

export function pgAdminConfigRepository(base: AggregateRepository<AdminConfig>, query: Query): AdminConfigRepository {
  let cached: Persisted<AdminConfig> | null = null;
  async function read(id: string, sections: AdminSectionsQuery = {}): Promise<Persisted<AdminConfig> | null> {
    for (;;) {
      const previous = cached;
      const rows = await query(`SELECT id, revision, updated_at, CASE WHEN revision = $2::bigint THEN NULL ELSE value END AS value
        FROM cp_admin_config WHERE id = $1`, [id, previous?.id === id ? previous.revision : null]);
      const row = rows[0];
      if (!row) { if (cached === previous) cached = null; return null; }
      const value = row.value === null ? previous!.value : (typeof row.value === "string" ? JSON.parse(row.value) : row.value) as AdminConfig;
      const snapshot = { id, revision: Number(row.revision), updatedAt: timestamp(row.updated_at), value };
      if (!cached || cached.id !== id || cached.revision <= snapshot.revision) cached = snapshot;
      const loaded: Record<string, unknown> = {};
      await Promise.all(Object.entries(sections).map(async ([name, selection]) => {
        const section = name as AdminSection;
        const options = selection === true ? {} : selection!;
        if (!(section in ADMIN_SECTIONS)) throw new Error("Unknown Admin section");
        const params: unknown[] = [id];
        const at = (v: unknown) => `$${params.push(v)}`;
        const filters = ["config_id = $1"];
        if (options.afterId !== undefined) filters.push(`id > ${at(options.afterId)}`);
        if (options.ids) filters.push(`id = ANY(${at(options.ids)}::text[])`);
        if (options.since) filters.push(`updated_at >= ${at(options.since)}::timestamptz`);
        if (options.where) {
          if (!options.where.path.length || options.where.path.some(key => !/^[a-zA-Z][a-zA-Z0-9]*$/.test(key))) throw new Error("Invalid Admin section path");
          const path = `value #>> '{${options.where.path.join(",")}}'`;
          filters.push(options.where.value === null ? `${path} IS NULL` : `${path} = ${at(options.where.value)}`);
        }
        if (options.pending && section === "fixList") filters.push("value->'dispatch' IS NOT NULL AND value #>> '{dispatch,honoredAt}' IS NULL");
        if (options.pending && section === "routineRefreshRequests") filters.push("(jsonb_array_length(value->'attempts') < (value->>'maximumAttempts')::integer OR value->'attempts' @> '[{\"finishedAt\":null}]'::jsonb)");
        if (options.activeAt && section === "routineDueRequests") filters.push(`value->>'withdrawnAt' IS NULL AND value->>'expiresAt' > ${at(options.activeAt)}`);
        for (const count of [options.limit, options.latestPerKey, options.activeAndRecent]) if (count !== undefined && (!Number.isSafeInteger(count) || count < 1)) throw new Error("Invalid Admin page size");
        if (options.activeAndRecent && section === "fixList") filters.push(`(value->>'state' != 'FIXED' OR id IN (SELECT id FROM cp_admin_fix_list WHERE config_id = $1 AND value->>'state' = 'FIXED' ORDER BY ordinal DESC LIMIT ${at(options.activeAndRecent)}))`);
        let selected = `SELECT id, value, ordinal FROM cp_admin_${ADMIN_SECTIONS[section]} WHERE ${filters.join(" AND ")}`;
        if (options.latestPerKey) selected = `SELECT id, value, ordinal FROM (SELECT id, value, ordinal, row_number() OVER (PARTITION BY value->>'key' ORDER BY ordinal DESC) AS rank FROM cp_admin_${ADMIN_SECTIONS[section]} WHERE ${filters.join(" AND ")}) ranked WHERE rank <= ${at(options.latestPerKey)}`;
        selected += ` ORDER BY ${options.afterId !== undefined ? "id ASC" : "ordinal DESC"}${options.limit ? ` LIMIT ${at(options.limit)}` : ""}`;
        if (options.includeIds?.length) selected = `SELECT id, value, ordinal FROM ((${selected}) UNION SELECT id, value, ordinal FROM cp_admin_${ADMIN_SECTIONS[section]} WHERE config_id = $1 AND id = ANY(${at(options.includeIds)}::text[])) included ORDER BY ${options.afterId !== undefined ? "id ASC" : "ordinal DESC"}`;
        const items = (await query(selected, params)).map(row => row.value);
        loaded[section] = options.afterId !== undefined ? items : items.reverse();
      }));
      if (Object.keys(sections).length) {
        const latest = await query("SELECT revision FROM cp_admin_config WHERE id = $1", [id]);
        if (Number(latest[0]?.revision) !== snapshot.revision) continue;
      }
      return { ...snapshot, value: copy({ ...currentSettings(snapshot.value), ...loaded }) };
    }
  }
  async function save(held: Persisted<AdminConfig> | null, next: AdminConfig, now: string): Promise<Persisted<AdminConfig>> {
    const id = held?.id ?? ADMIN_CONFIG_ID;
    const patch = changes(held?.value ?? null, next);
    if (held && !patch.length && canonicalJson(currentSettings(held.value)) === canonicalJson(currentSettings(next))) {
      const current = await read(id);
      if (current?.revision !== held.revision) throw new ConcurrentModification("AdminConfig", id, held.revision, current?.revision ?? null);
      return { ...current, value: copy(next) };
    }
    const params: unknown[] = [id, now, JSON.stringify(currentSettings(next)), held?.revision ?? null];
    const at = (value: unknown) => `$${params.push(value)}`;
    const clauses = [held
      ? `saved AS (UPDATE cp_admin_config SET revision = revision + 1, updated_at = $2::timestamptz, value = $3::jsonb WHERE id = $1 AND revision = $4::bigint RETURNING id, revision, updated_at)`
      : `saved AS (INSERT INTO cp_admin_config (id, revision, updated_at, value) SELECT $1, 1, $2::timestamptz, $3::jsonb WHERE $4::bigint IS NULL ON CONFLICT (id) DO NOTHING RETURNING id, revision, updated_at)`];
    for (const [index, change] of patch.entries()) {
      const table = `cp_admin_${ADMIN_SECTIONS[change.section]}`;
      if (change.put.length) clauses.push(`put_${index} AS (INSERT INTO ${table} (config_id, id, updated_at, value)
        SELECT saved.id, item->>'id', $2::timestamptz, item->'value' FROM saved CROSS JOIN jsonb_array_elements(${at(JSON.stringify(change.put))}::jsonb) item
        ON CONFLICT (config_id, id) DO UPDATE SET value = EXCLUDED.value, updated_at = EXCLUDED.updated_at RETURNING id)`);
      if (change.remove.length) clauses.push(`removed_${index} AS (DELETE FROM ${table} USING saved WHERE config_id = saved.id AND ${table}.id = ANY(${at(change.remove)}::text[]) RETURNING ${table}.id)`);
    }
    const rows = await query(`WITH ${clauses.join(",")} SELECT * FROM saved`, params);
    if (!rows.length) throw new ConcurrentModification("AdminConfig", id, held?.revision ?? 0, null);
    const saved = { id, revision: Number(rows[0].revision), updatedAt: timestamp(rows[0].updated_at), value: copy(currentSettings(next)) };
    if (!cached || cached.id !== id || cached.revision <= saved.revision) cached = saved;
    return { ...saved, value: copy(next) };
  }
  return adminMethods(base, read, save);
}

function adminMethods(base: AggregateRepository<AdminConfig>, read: AdminConfigRepository["read"], save: AdminConfigRepository["save"]): AdminConfigRepository {
  return {
    ...base, read, save,
    async mustRead(id, sections) { const row = await read(id, sections); if (!row) throw new UnknownAggregate("AdminConfig", id); return row; },
    async put(id, value, now) {
      if (id !== ADMIN_CONFIG_ID) throw new Error("Invalid Admin config id");
      const held = await read(id, scopeOf(value));
      if (!held) return { created: true, persisted: await save(null, value, now) };
      if (canonicalJson(held.value) !== canonicalJson(value)) throw new IdentityCollision("AdminConfig", id, canonicalJson(held.value), canonicalJson(value));
      return { created: false, persisted: held };
    },
    async compareAndSet(id, revision, value, now) {
      const held = await read(id, scopeOf(value));
      if (!held || held.revision !== revision) throw new ConcurrentModification("AdminConfig", id, revision, held?.revision ?? null);
      return save(held, value, now);
    },
  };
}

interface StoredAdminValue {
  readonly item: Record<string, unknown> | null;
  readonly ordinal: number;
  readonly updatedAt: string;
}
export interface StoredAdminSection extends StoredAdminValue {
  readonly configId: string;
  readonly pending?: StoredAdminValue & { readonly token: string; readonly revision: number };
}
interface StoredAdminCommit {
  readonly token: string;
  readonly rows: readonly { readonly section: AdminSection; readonly id: string }[];
  readonly nextOrdinal: number;
}
type StoredAdminConfig = AdminConfig & { readonly [COMMIT_KEY]?: StoredAdminCommit };

export async function migrateStoredAdminConfig(base: AggregateRepository<AdminConfig>, repo: AdminConfigRepository): Promise<void> {
  for (;;) {
    const held = await base.read(ADMIN_CONFIG_ID);
    if (!held || !Object.keys(ADMIN_SECTIONS).some(key => key in held.value)) return;
    try {
      await repo.save({ ...held, value: currentSettings(held.value) }, held.value, held.updatedAt);
      return;
    } catch (error) {
      if (!(error instanceof ConcurrentModification)) throw error;
    }
  }
}

export function storedAdminConfigRepository(base: AggregateRepository<AdminConfig>, sections: Record<AdminSection, AggregateRepository<StoredAdminSection>>, locks: LockManager): AdminConfigRepository {
  const rowId = (id: string, item: string) => `${id}:${item}`;
  const visible = (row: Persisted<StoredAdminSection>, head: Persisted<StoredAdminConfig>): StoredAdminValue => {
    const pending = row.value.pending;
    return pending?.revision === head.revision && pending.token === head.value[COMMIT_KEY]?.token ? pending : row.value;
  };
  async function read(id: string, query: AdminSectionsQuery = {}): Promise<Persisted<AdminConfig> | null> {
    for (;;) {
      const held = await base.read(id) as Persisted<StoredAdminConfig> | null;
      if (!held) return null;
      const loaded: Record<string, unknown> = {};
      for (const [name, selection] of Object.entries(query)) {
        const section = name as AdminSection;
        if (!(section in ADMIN_SECTIONS)) throw new Error("Unknown Admin section");
        const options = selection === true ? {} : selection!;
        for (const count of [options.limit, options.latestPerKey, options.activeAndRecent]) {
          if (count !== undefined && (!Number.isSafeInteger(count) || count < 1)) throw new Error("Invalid Admin page size");
        }
        const repo = sections[section];
        const rows = options.ids ? (await Promise.all(options.ids.map(item => repo.read(rowId(id, item))))).filter(row => row !== null) : await repo.listWhere(["configId"], id);
        const values = rows.map(row => visible(row, held));
        const extras = options.includeIds?.length
          ? (await Promise.all(options.includeIds.map(item => repo.read(rowId(id, item))))).filter(row => row !== null).map(row => visible(row, held)) : [];
        const ordinals = new Map([...values, ...extras].filter(row => row.item !== null).map(row => [itemId(section, row.item!), row.ordinal]));
        let items = values.filter(row => row.item !== null && (!options.since || row.updatedAt >= options.since))
          .sort((a, b) => a.ordinal - b.ordinal).map(row => row.item!);
        if (options.where) items = items.filter(item => {
          const value = options.where!.path.reduce<unknown>((at, key) => at && typeof at === "object" ? (at as Record<string, unknown>)[key] : undefined, item);
          return options.where!.value === null ? value == null : String(value) === options.where!.value;
        });
        if (options.pending && section === "fixList") items = items.filter(item => item.dispatch && !(item.dispatch as Record<string, unknown>).honoredAt);
        if (options.pending && section === "routineRefreshRequests") items = items.filter(item => (item.attempts as {finishedAt:string|null}[]).length < Number(item.maximumAttempts) || (item.attempts as {finishedAt:string|null}[]).some(attempt => attempt.finishedAt === null));
        if (options.activeAt && section === "routineDueRequests") items = items.filter(item => item.withdrawnAt === null && String(item.expiresAt) > options.activeAt!);
        if (options.latestPerKey) { const seen = new Map<unknown, number>(); items = items.slice().reverse().filter(item => { const n = (seen.get(item.key) ?? 0) + 1; seen.set(item.key, n); return n <= options.latestPerKey!; }).reverse(); }
        if (options.activeAndRecent && section === "fixList") {
          const recent = new Set(items.filter(item => item.state === "FIXED").slice(-options.activeAndRecent).map(item => item.id));
          items = items.filter(item => item.state !== "FIXED" || recent.has(item.id));
        }
        if (options.afterId !== undefined) items = items.filter(item => itemId(section, item) > options.afterId!).sort((a, b) => itemId(section, a).localeCompare(itemId(section, b)));
        let selected = options.limit ? (options.afterId !== undefined ? items.slice(0, options.limit) : items.slice(-options.limit)) : items;
        if (extras.length) {
          selected = [...new Map([...selected, ...extras.filter(row => row.item !== null).map(row => row.item!)].map(item => [itemId(section, item), item])).values()]
            .sort((a, b) => options.afterId !== undefined ? itemId(section, a).localeCompare(itemId(section, b)) : ordinals.get(itemId(section, a))! - ordinals.get(itemId(section, b))!);
        }
        loaded[section] = selected;
      }
      if (Object.keys(query).length && (await base.read(id))?.revision !== held.revision) continue;
      return { ...held, value: copy({ ...currentSettings(held.value), ...loaded }) };
    }
  }
  async function save(held: Persisted<AdminConfig> | null, next: AdminConfig, now: string): Promise<Persisted<AdminConfig>> {
    const id = held?.id ?? ADMIN_CONFIG_ID;
    return locks.withLock(`admin-config:${id}`, async () => {
      const current = await base.read(id) as Persisted<StoredAdminConfig> | null;
      if ((current?.revision ?? null) !== (held?.revision ?? null)) throw new ConcurrentModification("AdminConfig", id, held?.revision ?? 0, current?.revision ?? null);
      const patch = changes(held?.value ?? null, next);
      const priorCommit = current?.value[COMMIT_KEY];
      if (current && !patch.length && canonicalJson({ ...current.value, [COMMIT_KEY]: undefined }) === canonicalJson(currentSettings(next))) {
        return { ...current, value: copy(next) };
      }
      // Finalize only the last committed write; abandoned stages never become visible to a later revision.
      for (const changed of priorCommit?.rows ?? []) {
        const repo = sections[changed.section], key = rowId(id, changed.id), row = await repo.read(key);
        if (row?.value.pending?.token !== priorCommit!.token) continue;
        const { item, ordinal, updatedAt } = row.value.pending;
        await repo.compareAndSet(key, row.revision, { configId: id, item, ordinal, updatedAt }, updatedAt);
      }
      let nextOrdinal = priorCommit?.nextOrdinal ?? 0;
      const token = randomUUID();
      const written: { section: AdminSection; id: string }[] = [];
      for (const change of patch) {
        const repo = sections[change.section];
        for (const item of [...change.put, ...change.remove.map(id => ({ id, value: null }))]) {
          const key = rowId(id, item.id), old = await repo.read(key);
          const before = old && current ? visible(old, current) : { item: null, ordinal: 0, updatedAt: now };
          const ordinal = before.item === null ? ++nextOrdinal : before.ordinal;
          const record: StoredAdminSection = { configId: id, item: before.item, ordinal: before.ordinal, updatedAt: before.updatedAt,
            pending: { item: item.value, ordinal, updatedAt: now, token, revision: (current?.revision ?? 0) + 1 } };
          if (old) await repo.compareAndSet(key, old.revision, record, now);
          else await repo.put(key, record, now);
          written.push({ section: change.section, id: item.id });
        }
      }
      const stored: StoredAdminConfig = { ...currentSettings(next), [COMMIT_KEY]: { token, rows: written, nextOrdinal } };
      const saved = current ? await base.compareAndSet(id, current.revision, stored, now) : (await base.put(id, stored, now)).persisted;
      return { ...saved, value: copy(next) };
    });
  }
  return adminMethods(base, read, save);
}
