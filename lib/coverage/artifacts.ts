/**
 * The coverage manifest's SERVER-AND-SCRIPTS projection (AUD-06, g18).
 *
 * `./states.ts` is client-safe and holds three fields per state because that
 * is all the browser reads. This module holds everything else a build script
 * or a server module needs — the state's name, the county its geometry is
 * clipped to, and the filename of every artifact the pipeline generates for
 * it — and it is deliberately NOT client-safe by convention: nothing under
 * `components/` may import it, and `tests/coverage-manifest.test.ts` asserts
 * that no importer of this module is reachable from the browser graph.
 *
 * The split is not tidiness. The map is already 75% of the reader's initial
 * JavaScript; a manifest that centralised the wiring at the cost of shipping
 * county labels and roster filenames to every reader would have bought one
 * kind of correctness with another kind of defect.
 *
 * WHAT "ARTIFACT" MEANS HERE. Every filename below is GENERATED by a script
 * in this repo from an external source — it is not content someone wrote.
 * That is the line between this module and the per-state content tables
 * (`lib/area/facts.ts`, `lib/ballot/election-dates.ts` and their siblings),
 * which a manifest cannot generate and does not claim to. Onboarding a state
 * is one edit in `./states.ts` for the WIRING; the content is still work, and
 * the tests that hold those tables against the manifest are the list of it.
 */

import { COVERED_STATES, type CoveredState } from "./states.ts";

/** The election cycle whose ballot files are committed under `data/ballot`. */
export const BALLOT_CYCLE = "2026"; // expected-future: the cycle these files cover

/** A covered state, with everything off the browser's path. */
export interface StateCoverage extends CoveredState {
  /** The state's full name, as a reader-facing string. */
  name: string;
  /** Five-digit FIPS of the county the local geometry is clipped to. */
  countyFips: string;
  /** The county's name without the word "County". */
  countyName: string;
  /** Lower-case county name — the middle segment of a ballot filename. */
  countySlug: string;
}

/**
 * The per-state facts that are not on the browser's path.
 *
 * Keyed by FIPS and merged against `COVERED_STATES` below, so a state added to
 * the manifest without an entry here is a TypeScript error at build time
 * rather than an undefined at run time — which is the whole point of the row.
 */
const DETAIL: Readonly<
  Record<string, Omit<StateCoverage, keyof CoveredState>>
> = {
  "04": {
    name: "Arizona",
    countyFips: "04019",
    countyName: "Pima",
    countySlug: "pima",
  },
  "33": {
    name: "New Hampshire",
    countyFips: "33013",
    countyName: "Merrimack",
    countySlug: "merrimack",
  },
  "34": {
    name: "New Jersey",
    countyFips: "34027",
    countyName: "Morris",
    countySlug: "morris",
  },
};

/**
 * Every derived server-and-scripts list, as a function of the manifest.
 *
 * A function for the same reason `deriveClientLists` is one: the suite proves
 * the one-edit claim by calling it with a throwaway state appended and
 * asserting the extra state appears in every list it returns.
 *
 * Throws on a manifest state with no `DETAIL` row rather than skipping it. A
 * skip would render as a state that is covered everywhere except in the
 * artifacts it needs — an absence manufactured by a default, which is the one
 * shape this repo's render rule forbids everywhere else and has no business
 * being tolerated in the wiring.
 */
export function deriveArtifacts(
  states: readonly CoveredState[],
  detail: Readonly<
    Record<string, Omit<StateCoverage, keyof CoveredState>>
  > = DETAIL,
) {
  const full: StateCoverage[] = states.map((s) => {
    const d = detail[s.fips];
    if (!d) {
      throw new Error(
        `coverage manifest: state ${s.usps} (FIPS ${s.fips}) has no detail row — ` +
          `add one to lib/coverage/artifacts.ts`,
      );
    }
    return { ...s, ...d };
  });

  return {
    states: full,
    /** The generated officeholder roster per state, federal roster first. */
    rosters: ["officeholders-us.json", ...full.map(rosterFile)],
    /** USPS -> its roster filename. Was three separate tables in scripts/. */
    rosterByUsps: Object.fromEntries(full.map((s) => [s.usps, rosterFile(s)])),
    /** USPS -> the state's full name. Was `STATE_PLACE`. */
    nameByUsps: Object.fromEntries(full.map((s) => [s.usps, s.name])),
    /** The clipped counties the geo pipeline fetches. Was `CLIP_COUNTIES`. */
    clipCounties: full.map((s) => ({
      fips: s.countyFips,
      label: `${s.countyName} County, ${s.usps}`,
    })),
    /** The committed ballot file per state, for the current cycle. */
    ballotFiles: full.map((s) => ({ file: ballotFile(s), state: s.usps })),
  };
}

/** `officeholders-04.json` — the roster `pnpm officeholders:build` writes. */
export function rosterFile(state: StateCoverage | CoveredState): string {
  return `officeholders-${state.fips}.json`;
}

/** `az-pima-2026.json` — the committed ballot set under `data/ballot`. */
export function ballotFile(
  state: StateCoverage,
  cycle: string = BALLOT_CYCLE,
): string {
  return `${state.slug}-${state.countySlug}-${cycle}.json`;
}

const derived = deriveArtifacts(COVERED_STATES);

export const COVERED: readonly StateCoverage[] = derived.states;
export const ROSTER_FILES: readonly string[] = derived.rosters;
export const ROSTER_BY_USPS: Readonly<Record<string, string>> =
  derived.rosterByUsps;
export const NAME_BY_USPS: Readonly<Record<string, string>> = derived.nameByUsps;
export const CLIP_COUNTIES: readonly { fips: string; label: string }[] =
  derived.clipCounties;
export const BALLOT_FILES: readonly { file: string; state: string }[] =
  derived.ballotFiles;
