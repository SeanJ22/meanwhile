/**
 * **AGENTS.md IS THE NEXT.JS BLOCK PLUS A BYTE-EXACT GENERATED MIRROR OF
 * `CLAUDE.md`.** (Provider transition, 2026-09-02.)
 *
 * A coding agent that is not Claude Code reads `AGENTS.md` first and may never
 * open `CLAUDE.md`. Two hand-maintained copies of the root constitution would
 * diverge the way `docs/rulings.md` once diverged from `CLAUDE.md` (87 of 90
 * rulings, measured on 2026-08-26). So the project-law portion of `AGENTS.md`
 * is GENERATED from `CLAUDE.md`, and three existing gates hold it current:
 *
 * ```
 *   tests/generated-artifacts.test.ts   regenerates every registered pure
 *                                       artifact in place and compares bytes
 *                                       (RULING 92, RULING 102) — the suite,
 *                                       run by `pnpm gates` and by CI
 *   .githooks/pre-commit                `agents-sync.mjs --check` before a commit
 *   scripts/handoff.mjs                 the same check on the closeout checklist
 * ```
 *
 * The invariant this file states, and the generator keeps:
 *
 *   Everything operative in the root `CLAUDE.md` is supplied, verbatim, in
 *   the root `AGENTS.md`; `AGENTS.md` is never an authority of its own.
 *
 * ## Layout, and why the order is fixed
 *
 * ```
 *   <!-- BEGIN:nextjs-agent-rules -->  …  <!-- END:nextjs-agent-rules -->
 *       written and re-upserted by `next dev` (generate-agent-files.js);
 *       preserved byte-for-byte by this generator, never invented by it
 *   # MEANWHILE — INSTRUCTIONS FOR CODEX AND EVERY CODING AGENT
 *       the FIRST project-owned content after the Next block
 *       (tests/acquisition-doctrine.test.ts asserts nothing but whitespace
 *       sits between them)
 *   <!-- BEGIN:claude-md-mirror source=CLAUDE.md sha256=… bytes=… -->
 *       a notice sending the agent to docs/rulings.md, then CLAUDE.md verbatim
 *   <!-- END:claude-md-mirror -->
 * ```
 *
 * ## Bytes
 *
 * The comparison is over NORMALIZED text (BOM stripped, `\r\n` → `\n`), and
 * the digest in the marker is over normalized `CLAUDE.md`, so a CRLF working
 * copy and an LF blob agree. The generator writes with the line ending the
 * existing `AGENTS.md` already uses, exactly as Next's generator does, so
 * regenerating an unchanged file is a byte-for-byte no-op — which is what
 * the in-place regeneration test needs to pass.
 *
 * Plain `.mjs` on purpose: the pre-commit hook runs it with bare `node`.
 */

import { createHash } from "node:crypto";

export const NEXT_BEGIN = "<!-- BEGIN:nextjs-agent-rules -->";
export const NEXT_END = "<!-- END:nextjs-agent-rules -->";
export const MIRROR_BEGIN_PREFIX = "<!-- BEGIN:claude-md-mirror";
export const MIRROR_END = "<!-- END:claude-md-mirror -->";
export const LAW_HEADING = "# MEANWHILE — INSTRUCTIONS FOR CODEX AND EVERY CODING AGENT";
export const SYNC_COMMAND = "pnpm agents:sync";
export const CHECK_COMMAND = "pnpm agents:check";

/** BOM stripped, every line ending `\n`. The only form anything here compares. */
export function normalize(text) {
  return String(text).replace(/^﻿/, "").replace(/\r\n?/g, "\n");
}

export function sha256(text) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

/**
 * The notice at the head of the mirror. It sends the agent to Sean's standing
 * decisions, says the mirrored working guide binds it too, says what the
 * section is NOT, and how a disagreement resolves — an agent that finds the
 * mirror and `CLAUDE.md` disagreeing must not conclude that the file it has
 * open wins. (Since 2026-09-25 the standing decisions are `docs/rulings.md`
 * and `CLAUDE.md` is the working guide that applies them.)
 */
export function mirrorNotice() {
  return [
    "**Codex and every other coding agent: Sean's standing decisions are `docs/rulings.md`,",
    "the single source for owner policy. Read it first. It binds you exactly as it binds Claude.**",
    "",
    "The working guide below is a GENERATED, byte-exact mirror of `CLAUDE.md`. It sets the same",
    "working expectations for you; where it says \"Claude\", read it as the agent doing the work.",
    "It is not a separate version of Sean's policies and it is **NOT an authority of its own**:",
    "if this mirror and `CLAUDE.md` ever differ, `CLAUDE.md` is right and this file is stale.",
    `It is regenerated by \`${SYNC_COMMAND}\` and checked by \`${CHECK_COMMAND}\`, by the`,
    "pre-commit hook, by the closeout checklist, and by `tests/generated-artifacts.test.ts`,",
    "which regenerates it in place and compares bytes. Never edit anything below this notice",
    "by hand — change `CLAUDE.md` and regenerate.",
  ].join("\n");
}

/** The generated section, LF-normalized. */
export function renderMirrorSection(claudeText) {
  const body = normalize(claudeText);
  const withNewline = body.endsWith("\n") ? body : `${body}\n`;
  const digest = sha256(withNewline);
  return [
    LAW_HEADING,
    "",
    `${MIRROR_BEGIN_PREFIX} source=CLAUDE.md sha256=${digest} bytes=${Buffer.byteLength(withNewline, "utf8")} -->`,
    mirrorNotice(),
    "",
    withNewline + MIRROR_END,
    "",
  ].join("\n");
}

/**
 * Split an existing AGENTS.md into the Next block (kept) and the rest.
 * Refuses a file without the block: this generator never invents it, because
 * an absent block is exactly the state in which `next dev` overwrites
 * `CLAUDE.md` with a 12-byte stub (tracker R01).
 */
export function splitNextBlock(existingAgents) {
  const text = normalize(existingAgents);
  const start = text.indexOf(NEXT_BEGIN);
  const end = text.indexOf(NEXT_END, start);
  if (start < 0 || end < 0) {
    throw new Error(
      `AGENTS.md carries no ${NEXT_BEGIN} … ${NEXT_END} block. The generator preserves that ` +
        "block and never invents it; restore it (run `next dev` once, or take it from git) before regenerating.",
    );
  }
  const blockEnd = end + NEXT_END.length;
  return { nextBlock: text.slice(0, blockEnd), rest: text.slice(blockEnd) };
}

/** The whole file, LF-normalized: the preserved Next block, a blank line, the mirror. */
export function renderAgentsFile(existingAgents, claudeText) {
  const { nextBlock } = splitNextBlock(existingAgents);
  return `${nextBlock}\n\n${renderMirrorSection(claudeText)}`;
}

/** Which line ending the existing file uses; the generator writes with the same. */
export function lineEndingOf(existing) {
  return /\r\n/.test(String(existing)) ? "\r\n" : "\n";
}

/**
 * Is this AGENTS.md exactly what CLAUDE.md renders to? Names the first
 * differing line so a stale mirror is a finding, never a shrug.
 */
export function checkAgentsFile(existingAgents, claudeText) {
  let expected;
  try {
    expected = renderAgentsFile(existingAgents, claudeText);
  } catch (error) {
    return { ok: false, reason: error instanceof Error ? error.message : String(error) };
  }
  const actual = normalize(existingAgents);
  if (actual === expected) return { ok: true, reason: "AGENTS.md is the Next block plus the byte-exact mirror of CLAUDE.md" };
  const a = actual.split("\n");
  const e = expected.split("\n");
  let i = 0;
  while (i < a.length && i < e.length && a[i] === e[i]) i += 1;
  const markerOk = actual.includes(`${MIRROR_BEGIN_PREFIX} source=CLAUDE.md sha256=${sha256(normalize(claudeText).endsWith("\n") ? normalize(claudeText) : `${normalize(claudeText)}\n`)}`);
  return {
    ok: false,
    reason:
      `AGENTS.md is STALE against CLAUDE.md: first difference at line ${i + 1} ` +
      `(${JSON.stringify((a[i] ?? "<end of file>").slice(0, 80))} vs ${JSON.stringify((e[i] ?? "<end of file>").slice(0, 80))}); ` +
      `mirror digest ${markerOk ? "matches" : "does not match"} the current CLAUDE.md. Run \`${SYNC_COMMAND}\`; never hand-edit the mirror.`,
  };
}
