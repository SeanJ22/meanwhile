// Builds AGENTS.md: the Next.js block `next dev` maintains, then a copy of CLAUDE.md for Codex and other agents.

export const NEXT_BEGIN = "<!-- BEGIN:nextjs-agent-rules -->";
export const NEXT_END = "<!-- END:nextjs-agent-rules -->";
export const HEADING = "# Meanwhile — instructions for Codex and every coding agent";

export function normalize(text) {
  return String(text).replace(/^﻿/, "").replace(/\r\n?/g, "\n");
}

export function splitNextBlock(existingAgents) {
  const text = normalize(existingAgents);
  const start = text.indexOf(NEXT_BEGIN);
  const end = text.indexOf(NEXT_END, start);
  if (start < 0 || end < 0) {
    throw new Error(`AGENTS.md has no ${NEXT_BEGIN} … ${NEXT_END} block; run \`next dev\` once to restore it, then regenerate.`);
  }
  return text.slice(0, end + NEXT_END.length);
}

export function renderAgentsFile(existingAgents, claudeText) {
  const body = normalize(claudeText);
  return [
    splitNextBlock(existingAgents),
    "",
    HEADING,
    "",
    "This is a copy of `CLAUDE.md`, generated by `pnpm agents:sync`. Where it says Claude, read it as the agent doing the work.",
    "",
    body.endsWith("\n") ? body : `${body}\n`,
  ].join("\n");
}

export function lineEndingOf(existing) {
  return /\r\n/.test(String(existing)) ? "\r\n" : "\n";
}
