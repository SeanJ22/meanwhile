import assert from "node:assert/strict";
import { test } from "node:test";
import { loadBootstrapLookup } from "./helpers/census-geography-fixtures.ts";
import { declaredWorkMembers } from "../lib/control-plane/expansion/declared-work-scope.ts";
import { resolveScopes } from "../lib/control-plane/expansion/runner-load.ts";
import { withScopeSet } from "../lib/control-plane/expansion/scopes.ts";
import { buildTerritoryIndex, planExpansion, armExpansionBudget } from "../lib/control-plane/expansion/membership.ts";
import { planDispatchWork, scopeWorkTarget, applyDispatchWork } from "../lib/control-plane/expansion/dispatch-work.ts";
import { UNREAD_MEETING_PARTITIONS } from "../lib/control-plane/scheduler/provider-inputs.ts";
import { createMemoryRepositories } from "../lib/control-plane/repository/memory.ts";
import { standing } from "../lib/control-plane/scheduler/durable.ts";

test("a ZIP hunt reaches its shared candidates and finance, records the Send on existing work, and binds its token budget", async () => {
  const now = "2026-09-26T08:00:00Z";
  const decision = withScopeSet([], { geography: { type: "zcta", geoid: "85635", version: "zcta:2020", label: "ZIP 85635", stateAbbr: "AZ" }, priority: 1, budgetUsd: 50, huntBudget: true, note: null, decidedAt: now, decidedBy: "adm_test", receiptId: "test-send" }).scopes[0];
  const lookup = loadBootstrapLookup();
  const resolved = await resolveScopes([decision], { lookup, source: "published", versionId: "isolated-fixture" }, null);
  const make = (subjectId: string, division: string) => ({ id: `freshness:test:${subjectId}#route`, subjectId, scopeDivisions: [division] });
  const work = [make("az:shared-finance", "ocd-division/country:us/state:az"), make("az:cd6-candidate", "ocd-division/country:us/state:az/cd:6"), make("az:cd7-candidate", "ocd-division/country:us/state:az/cd:7"), make("nh:state-candidate", "ocd-division/country:us/state:nh")];
  work.push(make("us:shared-federal", "ocd-division/country:us"));
  const declaredMembers = await declaredWorkMembers(resolved.scopes, work, lookup);
  assert.deepEqual([...declaredMembers.get(decision.key)!].sort(), ["az:cd6-candidate", "az:shared-finance", "us:shared-federal"]);
  const territory = buildTerritoryIndex([], []);
  const plan = planExpansion({ now, scopes: resolved.scopes, malformedScopes: 0, lookup: resolved.lookup, territory, territoryDetail: null, obligations: work, declaredMembers });
  assert.equal(plan.placementOf("az:cd6-candidate"), 0);
  assert.equal(plan.placementOf("az:cd7-candidate"), null);
  assert.equal(plan.reading.territory.placedSubjects, 3);
  assert.equal(plan.reading.territory.unplacedSubjects, 2);
  const repos = createMemoryRepositories();
  for (const row of work) await repos.obligations.put(row.id, standing({ ...row, recordClass: "candidate-enrichment", routeId: "route", active: true, readerImpactAt: null, observedChangeRateHours: null, lastWorkedAt: null }, now), now);
  const world = { registries: new Map(), territory, territoryDetail: null, corpus: work, durable: new Map(work.map(row => [row.id, { active: true }])), meetingPartitions: UNREAD_MEETING_PARTITIONS };
  const dispatch = planDispatchWork({ targets: [scopeWorkTarget(plan.scopes[0])], world });
  assert.equal(dispatch.writes.length, 0, "shared work keeps its original clock");
  assert.equal(dispatch.marks.length, 3);
  await applyDispatchWork(repos, dispatch, { now });
  const held = await repos.obligations.mustRead(work[1].id);
  assert.equal(held.value.assignments?.[0]?.assignmentKey, decision.key);
  const again = planDispatchWork({ targets: [scopeWorkTarget(plan.scopes[0])], world: { ...world, durable: new Map((await repos.obligations.list()).map(row => [row.id, row.value])) } });
  assert.equal(again.marks.length, 0, "the next cycle reuses attribution");
  const budget = armExpansionBudget(plan, { now, charges: [], worstCaseUsd: 10 }).gate;
  assert.equal(budget.bindingScopes("az:cd6-candidate")[0].budgetUsd, 50);
  assert.equal(budget.bindingScopes("az:cd7-candidate").length, 0);
  assert.equal(budget.bindingScopes("us:shared-federal")[0].budgetUsd, 50);
});
