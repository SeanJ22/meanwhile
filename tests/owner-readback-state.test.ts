import assert from "node:assert/strict";
import test from "node:test";
import { PGlite } from "@electric-sql/pglite";
import { readOwnerTotals,readOwnerStateReadback,writeOwnerStateReadback } from "../lib/control-plane/owner-readback-state.ts";
import { createMemoryRepositories } from "../lib/control-plane/repository/memory.ts";
import type { Sql } from "../lib/control-plane/repository/pg-store.ts";
import type { ServedReaderWitness } from "../lib/control-plane/served-reader.ts";
import { EXACT_SERVED_WITNESS_SQL } from "../lib/control-plane/admin-view/public-reader-observation-read.ts";
import { ZIP_WITNESS_SQL } from "../lib/control-plane/admin-view/v6-results-read.ts";

test("owner totals and legacy readback transfer only identities and the selected state's witnesses; Admin also reads new shards",async t=>{
  const pg=new PGlite();t.after(()=>pg.close());const repos=createMemoryRepositories();
  await pg.exec("CREATE TABLE cp_owner_snapshots(id text primary key,revision int,updated_at timestamptz,value jsonb); CREATE TABLE cp_work_items(id text primary key,value jsonb)");
  const witness=(id:string,stateCode:string):ServedReaderWitness=>({itemId:id,approvalId:`approval-${id}`,versionId:`version-${id}`,readerKey:`body:${stateCode}:board`,url:`https://meanwhile.club/ballot?zip=${stateCode==='az'?'85635':'07001'}`,checkedAt:"2026-10-20T12:00:00.000Z",state:"CONFIRMED",reason:"Observed",responseSha256:null});
  const az=witness("az-work","az"),nj={...witness("nj-work","nj"),reason:"FOREIGN_EVIDENCE".repeat(100_000)};
  await pg.query("INSERT INTO cp_owner_snapshots VALUES($1,1,now(),$2)",["current",JSON.stringify({servedReaderReadback:{checkedAt:az.checkedAt,witnesses:[az,nj],errors:[]}})]);
  await pg.query("INSERT INTO cp_owner_snapshots VALUES('totals',1,now(),$1)",[JSON.stringify({formatVersion:3,costs:null,assignments:{states:{az:{builtAt:az.checkedAt,publications:[{id:az.itemId,autonomousPlan:{source:"FOREIGN_EVIDENCE".repeat(100_000)}}]},nj:{builtAt:az.checkedAt,publications:[{id:nj.itemId}]}}}})]);
  const transmitted:unknown[]=[];
  const sql:Sql={query:async(text,params)=>{const result=await pg.query(text,params as unknown[]);transmitted.push(result.rows);return result.rows;}};
  const totals=await readOwnerTotals(repos,sql);
  assert.deepEqual(totals?.value.assignments?.states.az.publicationIds,[az.itemId]);
  assert.equal("publications" in totals!.value.assignments!.states.az,false);
  const legacy=await readOwnerStateReadback(repos,"AZ",sql);
  assert.deepEqual(legacy?.witnesses,[az]);
  assert.ok(!JSON.stringify(transmitted).includes("FOREIGN_EVIDENCE"),"country evidence never crosses the connection");
  const next={checkedAt:az.checkedAt,witnesses:[{...az,stateCode:"AZ"}],errors:[]};
  await writeOwnerStateReadback(repos,"AZ",next,az.checkedAt);
  assert.deepEqual(await readOwnerStateReadback(repos,"AZ",null),next);
  await pg.query("UPDATE cp_owner_snapshots SET value=$1 WHERE id='current'",[JSON.stringify({servedReaderReadback:{checkedAt:az.checkedAt,witnesses:[],stateScopes:["az"],witnessCount:1,errors:[]}})]);
  await pg.query("INSERT INTO cp_owner_snapshots VALUES('readback:az',1,now(),$1)",[JSON.stringify({servedReader:next})]);
  assert.equal((await pg.query(EXACT_SERVED_WITNESS_SQL,[az.itemId,az.approvalId,az.versionId])).rows.length,1);
  assert.equal((await pg.query(ZIP_WITNESS_SQL,[az.url])).rows.length,1);
});
